/**
 * Formal Nepali letters, ready to fill in.
 *
 * A निवेदन has a shape everyone in an office expects — where the date sits,
 * that the subject line is called विषय, that it closes with भवदीय. Getting it
 * wrong is not a spelling mistake, it is the letter being taken less
 * seriously. Almost nobody writes enough of them to remember the shape, and
 * looking one up means leaving the phone and finding a sample.
 *
 * These live in settings rather than on the keyboard on purpose. A निवेदन is
 * fifteen lines with blanks in it; you need to see the whole thing to fill it
 * in, which a chat box will not let you do. Paste it where the letter is
 * actually being written instead.
 *
 * The blanks are square brackets so they are impossible to miss and easy to
 * find again — no `_____` that reads as a formatting accident.
